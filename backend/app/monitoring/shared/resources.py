"""Resource manager seam. The platform object is still passed in."""
from __future__ import annotations

from typing import Protocol


class ResourceSource(Protocol):
    source: str
    prometheus_connected: bool

    def resources(self, kind: str | None = None): ...
    def timeseries(self, resource_type: str, resource_id: str, metric: str, start: int, end: int, step: int): ...
    def timeseries_grouped(self, metric: str, start: int, end: int, step: int): ...
    def resource_snapshot(self): ...
    def request_refresh(self) -> None: ...
